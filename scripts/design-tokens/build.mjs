#!/usr/bin/env node
// Emits platform theme modules from design/tokens.json — the only place colors live.
import { readFileSync, writeFileSync, mkdirSync } from "node:fs";
import { dirname, join, relative, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const repoRoot = resolve(here, "..", "..");
const mobileRoot = join(repoRoot, "aura-music-mobile");
const tokens = JSON.parse(readFileSync(join(repoRoot, "design", "tokens.json"), "utf8"));

const flatten = (obj, prefix = "") =>
  Object.entries(obj).flatMap(([key, value]) => {
    const name = prefix ? `${prefix}_${key}` : key;
    if (value && typeof value === "object" && !Array.isArray(value)) return flatten(value, name);
    return [[name, value]];
  });

// token keys like "ink_0" or "gold_500" become valid identifiers: ink0, gold500
const ident = (key) => key.replace(/_(\d)/g, "$1").replace(/^(\d)/, "x$1");

const jsObject = (entries, indent = "  ") =>
  `{\n${entries.map(([k, v]) => `${indent}${k}: ${JSON.stringify(v)},`).join("\n")}\n}`;

const jsRawObject = (entries, indent = "  ") =>
  `{\n${entries.map(([k, v]) => `${indent}${k}: ${v},`).join("\n")}\n}`;

const colorEntries = flatten(tokens.color).map(([key, value]) => [ident(key), value]);
const spaceEntries = Object.entries(tokens.space).map(([k, v]) => [`s${k}`, v]);
const radiusEntries = Object.entries(tokens.radius).map(([k, v]) => [k, v]);
const sizeEntries = Object.entries(tokens.size).map(([k, v]) => [k, v]);
const elevationEntries = Object.entries(tokens.elevation).map(([k, v]) => [k, v]);

const typeEntries = Object.entries(tokens.type).map(
  ([key, v]) =>
    `  ${key}: {\n` +
    `    fontFamily: ${JSON.stringify(v.font)},\n` +
    `    fontSize: ${v.size},\n` +
    `    lineHeight: ${v.line},\n` +
    `    letterSpacing: ${v.tracking},\n` +
    `  } as TextStyle,`,
);

const fontFileEntries = Object.entries(tokens.font.files).map(([key, path]) => [
  key,
  `require(${JSON.stringify(relative(join(mobileRoot, "src", "theme"), resolve(mobileRoot, path.replace(/^\.\//, ""))).replace(/\\/g, "/"))})`,
]);

const out = `// AUTO-GENERATED by scripts/design-tokens/build.mjs — edit design/tokens.json instead.
/* eslint-disable */
import type { TextStyle } from "react-native";

export const Color = ${jsObject(colorEntries)} as const;

export const Gradient = ${JSON.stringify(tokens.gradient, null, 2)} as const;

export const Space = ${jsObject(spaceEntries)};

export const Radius = ${jsObject(radiusEntries)};

export const Size = ${jsObject(sizeEntries)};

export const Elevation = ${jsObject(elevationEntries)};

export const FontFamily = ${JSON.stringify({ display: tokens.font.display, ui: tokens.font.ui }, null, 2)};

export const FontFiles = ${jsRawObject(fontFileEntries, "  ")};

export const Motion = ${JSON.stringify(tokens.motion, null, 2)};

export const Type = {
${typeEntries.join("\n")}
};

export type ColorToken = keyof typeof Color;
`;

const target = join(mobileRoot, "src", "theme", "tokens.ts");
mkdirSync(dirname(target), { recursive: true });
writeFileSync(target, out, "utf8");
console.log(`wrote ${relative(repoRoot, target)} (${out.split("\n").length} lines)`);
