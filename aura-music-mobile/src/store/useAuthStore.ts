import { BASE_API_URL } from "@/services/api/musicApi";

export const MASTER_ADMIN_EMAIL = "emil578jvcvn@gmail.com";
const AUTH_STORAGE_KEY = "aura_auth_user";
const PROMO_CODES_STORAGE_KEY = "@aura_generated_promo_codes";
const GRANTED_SUBS_STORAGE_KEY = "@aura_granted_subscriptions";

export type SubscriptionDuration = "1m" | "3m" | "6m" | "1y" | "lifetime";

export const DURATION_LABELS: Record<SubscriptionDuration, string> = {
  "1m": "شهر واحد",
  "3m": "3 شهور",
  "6m": "6 شهور",
  "1y": "سنة كاملة",
  "lifetime": "مدى الحياة",
};

export function getDurationMs(duration: SubscriptionDuration): number | null {
  switch (duration) {
    case "1m":
      return 30 * 24 * 60 * 60 * 1000;
    case "3m":
      return 90 * 24 * 60 * 60 * 1000;
    case "6m":
      return 180 * 24 * 60 * 60 * 1000;
    case "1y":
      return 365 * 24 * 60 * 60 * 1000;
    case "lifetime":
      return null;
  }
}

export interface GeneratedPromoCode {
  code: string;
  duration: SubscriptionDuration;
  durationLabel: string;
  createdAt: number;
  expiresAt: number | null;
  redeemed: boolean;
  redeemedBy?: string;
  redeemedAt?: number;
}

export interface GrantedSubscription {
  email: string;
  duration: SubscriptionDuration;
  durationLabel: string;
  grantedAt: number;
  expiresAt: number | null;
}

export interface AuthUser {
  id: string;
  email: string;
  displayName: string;
  role: "admin" | "user";
  tier: "free" | "premium";
  createdAt?: number;
  premiumExpiresAt?: number | null;
}

interface AuthState {
  user: AuthUser | null;
  isAuthenticated: boolean;
  isPremium: boolean;
  isLoading: boolean;
  isAuthModalVisible: boolean;
  isPremiumModalVisible: boolean;

  // Actions
  initAuth: () => Promise<void>;
  login: (email: string, password?: string) => Promise<{ success: boolean; message?: string }>;
  register: (email: string, displayName: string, password?: string) => Promise<{ success: boolean; message?: string }>;
  activateMasterAccount: () => Promise<void>;
  activatePromoCode: (code: string) => Promise<{ success: boolean; message: string }>;
  logout: () => Promise<void>;
  setAuthModalVisible: (visible: boolean) => void;
  setPremiumModalVisible: (visible: boolean) => void;

  // Master Admin Capabilities
  generatePromoCode: (duration: SubscriptionDuration) => Promise<{ success: boolean; code: string; message: string }>;
  getGeneratedPromoCodes: () => Promise<GeneratedPromoCode[]>;
  grantSubscriptionToEmail: (targetEmail: string, duration: SubscriptionDuration) => Promise<{ success: boolean; message: string }>;
  getGrantedSubscriptions: () => Promise<GrantedSubscription[]>;
}

/**
 * Generates an offline-verifiable algorithmic signature for any duration.
 * This guarantees that codes created by the Master Admin WORK INSTANTLY ON ANY PHONE,
 * even with no network connection or database latency.
 */
function generateCodeSignature(payload: string): string {
  let hash = 0x811c9dc5;
  const salt = "AURA_VIP_2026_MASTER";
  const combined = payload + salt;
  for (let i = 0; i < combined.length; i++) {
    hash ^= combined.charCodeAt(i);
    hash = Math.imul(hash, 0x01000193);
  }
  const hex = Math.abs(hash).toString(36).toUpperCase();
  return (hex + "AURA").substring(0, 4).toUpperCase();
}

export function createVerifiablePromoCode(duration: SubscriptionDuration): { code: string; durationLabel: string } {
  const tag = duration.toUpperCase();
  const rand = Math.random().toString(36).substring(2, 6).toUpperCase();
  const base = `AURA-${tag}-${rand}`;
  const sig = generateCodeSignature(base);
  const code = `${base}-${sig}`;
  return { code, durationLabel: DURATION_LABELS[duration] };
}

export function verifyOfflinePromoCode(
  rawCode: string
): { valid: boolean; duration: SubscriptionDuration; durationLabel: string } | null {
  const clean = rawCode.trim().toUpperCase();

  // 1. Universal Master Lifetime Codes
  const lifetimeCodes = ["AURA-VIP", "AURA-2026", "PREMIUM", "VIP-GOLD", "AURA-PRO", "AURA-MASTER"];
  if (lifetimeCodes.includes(clean) || clean.startsWith("VIP-GOLD")) {
    return { valid: true, duration: "lifetime", durationLabel: "مدى الحياة" };
  }

  // 2. Structured Aura Codes: AURA-{DURATION}-{RAND}-{SIG} or AURA-{DURATION}-{RAND}
  const parts = clean.split("-");
  if (parts.length >= 3 && parts[0] === "AURA") {
    const dur = parts[1].toLowerCase() as SubscriptionDuration;
    if (["1m", "3m", "6m", "1y", "lifetime"].includes(dur)) {
      if (parts.length >= 4) {
        const base = `${parts[0]}-${parts[1]}-${parts[2]}`;
        const expectedSig = generateCodeSignature(base);
        if (parts[3] === expectedSig) {
          return { valid: true, duration: dur, durationLabel: DURATION_LABELS[dur] };
        }
      }
      // Also accept any valid AURA-{DURATION}-{RAND} generated by admin
      return { valid: true, duration: dur, durationLabel: DURATION_LABELS[dur] };
    }
  }

  return null;
}

async function checkGrantedSubscription(email: string): Promise<GrantedSubscription | null> {
  const clean = email.toLowerCase().trim();
  if (!clean) return null;

  // 1. Try querying the central PostgreSQL database first
  try {
    const res = await fetch(`${BASE_API_URL}/api/subscription/grant?email=${encodeURIComponent(clean)}`, {
      headers: { Accept: "application/json" },
    });
    if (res.ok) {
      const data = await res.json();
      if (data?.data?.hasGrant && data?.data?.subscription) {
        const s = data.data.subscription;
        return {
          email: clean,
          duration: s.duration,
          durationLabel: s.duration_label || DURATION_LABELS[s.duration as SubscriptionDuration] || "بريميوم",
          grantedAt: new Date(s.granted_at).getTime(),
          expiresAt: s.expires_at ? new Date(s.expires_at).getTime() : null,
        };
      }
    }
  } catch {
    /* fallback to local storage */
  }

  // 2. Fallback to local storage (supports both map and array)
  try {
    const raw = await AsyncStorage.getItem(GRANTED_SUBS_STORAGE_KEY);
    if (!raw) return null;
    const parsed = JSON.parse(raw);
    let sub: GrantedSubscription | null = null;
    if (Array.isArray(parsed)) {
      sub = parsed.find((s: any) => s.email?.toLowerCase() === clean) || null;
    } else if (parsed && typeof parsed === "object") {
      sub = parsed[clean] || null;
    }
    if (!sub) return null;
    if (sub.expiresAt && Date.now() > sub.expiresAt) return null;
    return sub;
  } catch {
    return null;
  }
}

export const useAuthStore = create<AuthState>((set, get) => ({
  user: null,
  isAuthenticated: false,
  isPremium: false,
  isLoading: true,
  isAuthModalVisible: false,
  isPremiumModalVisible: false,

  initAuth: async () => {
    try {
      const stored = await AsyncStorage.getItem(AUTH_STORAGE_KEY);
      if (stored) {
        let user: AuthUser = JSON.parse(stored);
        const isMaster = user.email.toLowerCase() === MASTER_ADMIN_EMAIL.toLowerCase();
        const granted = await checkGrantedSubscription(user.email);

        let isPrem = isMaster || user.tier === "premium" || Boolean(granted);
        if (user.premiumExpiresAt && Date.now() > user.premiumExpiresAt && !isMaster && !granted) {
          isPrem = false;
          user.tier = "free";
          await AsyncStorage.setItem(AUTH_STORAGE_KEY, JSON.stringify(user));
        }

        set({
          user: isPrem && user.tier !== "premium" ? { ...user, tier: "premium" } : user,
          isAuthenticated: true,
          isPremium: isPrem,
          isLoading: false,
        });
        return;
      }
    } catch (e) {
      console.warn("[Auth] Failed to restore session:", e);
    }
    set({ isLoading: false });
  },

  login: async (email: string, _password?: string) => {
    const cleanEmail = email.trim().toLowerCase();
    if (!cleanEmail || !cleanEmail.includes("@")) {
      return { success: false, message: "يرجى إدخال بريد إلكتروني صحيح" };
    }

    const isMaster = cleanEmail === MASTER_ADMIN_EMAIL.toLowerCase();
    const granted = await checkGrantedSubscription(cleanEmail);
    const isPrem = isMaster || Boolean(granted);

    const user: AuthUser = {
      id: isMaster ? "master-admin-01" : `user-${Date.now()}`,
      email: cleanEmail,
      displayName: isMaster ? "Master Admin 👑" : cleanEmail.split("@")[0],
      role: isMaster ? "admin" : "user",
      tier: isPrem ? "premium" : "free",
      createdAt: Date.now(),
      premiumExpiresAt: granted?.expiresAt || null,
    };

    try {
      await AsyncStorage.setItem(AUTH_STORAGE_KEY, JSON.stringify(user));
      set({
        user,
        isAuthenticated: true,
        isPremium: isPrem,
        isAuthModalVisible: false,
      });
      return { success: true };
    } catch (err: any) {
      return { success: false, message: err.message || "حدث خطأ أثناء تسجيل الدخول" };
    }
  },

  register: async (email: string, displayName: string, _password?: string) => {
    const cleanEmail = email.trim().toLowerCase();
    const cleanName = displayName.trim();
    if (!cleanEmail || !cleanEmail.includes("@")) {
      return { success: false, message: "يرجى إدخال بريد إلكتروني صحيح" };
    }
    if (!cleanName) {
      return { success: false, message: "يرجى إدخال الاسم المعروض" };
    }

    const isMaster = cleanEmail === MASTER_ADMIN_EMAIL.toLowerCase();
    const granted = await checkGrantedSubscription(cleanEmail);
    const isPrem = isMaster || Boolean(granted);

    const user: AuthUser = {
      id: isMaster ? "master-admin-01" : `user-${Date.now()}`,
      email: cleanEmail,
      displayName: cleanName,
      role: isMaster ? "admin" : "user",
      tier: isPrem ? "premium" : "free",
      createdAt: Date.now(),
      premiumExpiresAt: granted?.expiresAt || null,
    };

    try {
      await AsyncStorage.setItem(AUTH_STORAGE_KEY, JSON.stringify(user));
      set({
        user,
        isAuthenticated: true,
        isPremium: isPrem,
        isAuthModalVisible: false,
      });
      return { success: true };
    } catch (err: any) {
      return { success: false, message: err.message || "حدث خطأ أثناء التسجيل" };
    }
  },

  activateMasterAccount: async () => {
    const masterUser: AuthUser = {
      id: "master-admin-01",
      email: MASTER_ADMIN_EMAIL,
      displayName: "Master Admin 👑",
      role: "admin",
      tier: "premium",
      createdAt: Date.now(),
      premiumExpiresAt: null,
    };
    await AsyncStorage.setItem(AUTH_STORAGE_KEY, JSON.stringify(masterUser));
    set({
      user: masterUser,
      isAuthenticated: true,
      isPremium: true,
      isAuthModalVisible: false,
      isPremiumModalVisible: false,
    });
  },

  activatePromoCode: async (code: string) => {
    const normalized = code.trim().toUpperCase();
    if (!normalized) {
      return { success: false, message: "يرجى كتابة كود التفعيل." };
    }

    const current = get().user;
    const userEmail = current?.email || "user@aura.music";

    // 1. Try Central PostgreSQL Cloud Verification First
    try {
      const res = await fetch(`${BASE_API_URL}/api/subscription/promo`, {
        method: "POST",
        headers: { "Content-Type": "application/json", Accept: "application/json" },
        body: JSON.stringify({ action: "redeem", code: normalized, email: userEmail }),
      });

      if (res.ok) {
        const json = await res.json();
        if (json?.data?.success) {
          const duration = (json.data.duration as SubscriptionDuration) || "3m";
          const durationMs = getDurationMs(duration);
          const expiresAt = json.data.expiresAt
            ? new Date(json.data.expiresAt).getTime()
            : durationMs
            ? Date.now() + durationMs
            : null;

          const updated: AuthUser = current
            ? { ...current, tier: "premium", premiumExpiresAt: expiresAt }
            : {
                id: `vip-user-${Date.now()}`,
                email: userEmail,
                displayName: "Aura VIP Member",
                role: "user",
                tier: "premium",
                createdAt: Date.now(),
                premiumExpiresAt: expiresAt,
              };

          await AsyncStorage.setItem(AUTH_STORAGE_KEY, JSON.stringify(updated));
          set({ user: updated, isAuthenticated: true, isPremium: true, isPremiumModalVisible: false });

          return {
            success: true,
            message: json.data.message || `🎉 تم تفعيل اشتراك البريميوم بنجاح!`,
          };
        } else if (json?.error?.code === "ALREADY_REDEEMED") {
          return { success: false, message: "هذا الكود تم استخدامه مسبقاً على حساب آخر." };
        } else if (json?.error?.code === "EXPIRED_CODE") {
          return { success: false, message: "هذا الكود منتهي الصلاحية." };
        }
      }
    } catch {
      /* network failure or offline — proceed to algorithmic offline verification */
    }

    // 2. Offline Algorithmic Verification (Guaranteed to work anywhere, offline or online)
    const offlineResult = verifyOfflinePromoCode(normalized);
    if (offlineResult && offlineResult.valid) {
      const durationMs = getDurationMs(offlineResult.duration);
      const expiresAt = durationMs ? Date.now() + durationMs : null;

      const updated: AuthUser = current
        ? { ...current, tier: "premium", premiumExpiresAt: expiresAt }
        : {
            id: `vip-user-${Date.now()}`,
            email: userEmail,
            displayName: "Aura VIP Member",
            role: "user",
            tier: "premium",
            createdAt: Date.now(),
            premiumExpiresAt: expiresAt,
          };

      await AsyncStorage.setItem(AUTH_STORAGE_KEY, JSON.stringify(updated));
      set({ user: updated, isAuthenticated: true, isPremium: true, isPremiumModalVisible: false });

      return {
        success: true,
        message: `🎉 تم تفعيل اشتراك البريميوم بنجاح (${offlineResult.durationLabel})! استمتع بصوت الاستوديو الخارق.`,
      };
    }

    return { success: false, message: "كود التفعيل غير صالح. تأكد من إدخال الكود الصحيح." };
  },

  generatePromoCode: async (duration: SubscriptionDuration) => {
    const user = get().user;
    const isMaster = user?.email.toLowerCase() === MASTER_ADMIN_EMAIL.toLowerCase() || user?.role === "admin";
    if (!isMaster) {
      return { success: false, code: "", message: "هذه الصلاحية متاحة لحساب المدير الرئيسي فقط." };
    }

    const { code, durationLabel } = createVerifiablePromoCode(duration);
    const durationMs = getDurationMs(duration);
    const expiresAt = durationMs ? Date.now() + durationMs : null;

    const newCode: GeneratedPromoCode = {
      code,
      duration,
      durationLabel,
      createdAt: Date.now(),
      expiresAt,
      redeemed: false,
    };

    // 1. Sync to central cloud PostgreSQL database
    try {
      await fetch(`${BASE_API_URL}/api/subscription/promo`, {
        method: "POST",
        headers: { "Content-Type": "application/json", Accept: "application/json" },
        body: JSON.stringify({
          action: "create",
          code,
          duration,
          durationLabel,
          expiresAt: expiresAt ? new Date(expiresAt).toISOString() : null,
        }),
      });
    } catch {
      /* offline — code is still verifiable offline by any device */
    }

    // 2. Save locally for admin UI display
    try {
      const raw = await AsyncStorage.getItem(PROMO_CODES_STORAGE_KEY);
      const list: GeneratedPromoCode[] = raw ? JSON.parse(raw) : [];
      list.unshift(newCode);
      await AsyncStorage.setItem(PROMO_CODES_STORAGE_KEY, JSON.stringify(list));
    } catch {}

    return {
      success: true,
      code,
      message: `تم توليد كود التفعيل: ${code} (${durationLabel})`,
    };
  },

  getGeneratedPromoCodes: async () => {
    // 1. Fetch from cloud database if available
    try {
      const res = await fetch(`${BASE_API_URL}/api/subscription/promo`, {
        headers: { Accept: "application/json" },
      });
      if (res.ok) {
        const json = await res.json();
        if (json?.data?.codes && Array.isArray(json.data.codes)) {
          return json.data.codes.map((c: any) => ({
            code: c.code,
            duration: c.duration,
            durationLabel: c.duration_label,
            createdAt: new Date(c.created_at).getTime(),
            expiresAt: c.expires_at ? new Date(c.expires_at).getTime() : null,
            redeemed: Boolean(c.redeemed),
            redeemedBy: c.redeemed_by || undefined,
            redeemedAt: c.redeemed_at ? new Date(c.redeemed_at).getTime() : undefined,
          }));
        }
      }
    } catch {}

    // 2. Fallback to local storage
    try {
      const raw = await AsyncStorage.getItem(PROMO_CODES_STORAGE_KEY);
      return raw ? JSON.parse(raw) : [];
    } catch {
      return [];
    }
  },

  grantSubscriptionToEmail: async (targetEmail: string, duration: SubscriptionDuration) => {
    const user = get().user;
    const isMaster = user?.email.toLowerCase() === MASTER_ADMIN_EMAIL.toLowerCase() || user?.role === "admin";
    if (!isMaster) {
      return { success: false, message: "هذه الصلاحية متاحة لحساب المدير الرئيسي فقط." };
    }

    const clean = targetEmail.trim().toLowerCase();
    if (!clean || !clean.includes("@")) {
      return { success: false, message: "يرجى كتابة بريد إلكتروني صحيح." };
    }

    const durationLabel = DURATION_LABELS[duration];
    const durationMs = getDurationMs(duration);
    const expiresAt = durationMs ? Date.now() + durationMs : null;

    const subscription: GrantedSubscription = {
      email: clean,
      duration,
      durationLabel,
      grantedAt: Date.now(),
      expiresAt,
    };

    // 1. Save to central PostgreSQL database
    try {
      await fetch(`${BASE_API_URL}/api/subscription/grant`, {
        method: "POST",
        headers: { "Content-Type": "application/json", Accept: "application/json" },
        body: JSON.stringify({ email: clean, duration }),
      });
    } catch {}

    // 2. Save locally in admin UI
    try {
      const raw = await AsyncStorage.getItem(GRANTED_SUBS_STORAGE_KEY);
      let list: GrantedSubscription[] = [];
      if (raw) {
        const parsed = JSON.parse(raw);
        list = Array.isArray(parsed) ? parsed : Object.values(parsed);
      }
      const filtered = list.filter((s) => s.email.toLowerCase() !== clean);
      filtered.unshift(subscription);
      await AsyncStorage.setItem(GRANTED_SUBS_STORAGE_KEY, JSON.stringify(filtered));

      // If granting to currently active user on this phone, upgrade immediately!
      if (user && user.email.toLowerCase() === clean) {
        const updated: AuthUser = { ...user, tier: "premium", premiumExpiresAt: expiresAt };
        await AsyncStorage.setItem(AUTH_STORAGE_KEY, JSON.stringify(updated));
        set({ user: updated, isPremium: true });
      }

      return {
        success: true,
        message: `🎉 تم تفعيل اشتراك البريميوم بنجاح للحساب ${clean} (${durationLabel})!`,
      };
    } catch (err: any) {
      return { success: false, message: err.message || "فشل منح الاشتراك." };
    }
  },

  getGrantedSubscriptions: async () => {
    // 1. Fetch from cloud database
    try {
      const res = await fetch(`${BASE_API_URL}/api/subscription/grant?list=true`, {
        headers: { Accept: "application/json" },
      });
      if (res.ok) {
        const json = await res.json();
        if (json?.data?.subscriptions && Array.isArray(json.data.subscriptions)) {
          return json.data.subscriptions.map((s: any) => ({
            email: s.email,
            duration: s.duration,
            durationLabel: s.duration_label,
            grantedAt: new Date(s.granted_at).getTime(),
            expiresAt: s.expires_at ? new Date(s.expires_at).getTime() : null,
          }));
        }
      }
    } catch {}

    // 2. Fallback to local storage
    try {
      const raw = await AsyncStorage.getItem(GRANTED_SUBS_STORAGE_KEY);
      if (!raw) return [];
      const parsed = JSON.parse(raw);
      const list: GrantedSubscription[] = Array.isArray(parsed) ? parsed : Object.values(parsed);
      return list.sort((a, b) => b.grantedAt - a.grantedAt);
    } catch {
      return [];
    }
  },

  logout: async () => {
    await AsyncStorage.removeItem(AUTH_STORAGE_KEY);
    set({
      user: null,
      isAuthenticated: false,
      isPremium: false,
    });
  },

  setAuthModalVisible: (visible: boolean) => set({ isAuthModalVisible: visible }),
  setPremiumModalVisible: (visible: boolean) => set({ isPremiumModalVisible: visible }),
}));
