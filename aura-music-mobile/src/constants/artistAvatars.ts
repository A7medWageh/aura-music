/**
 * Returns a verified CDN portrait for an artist name.
 * Uses exact match first, then specific substring matching.
 */
export function getArtistAvatar(name?: string | null): string | null {
  if (!name || typeof name !== "string") return null;
  const clean = name.trim().toLowerCase();

  // 1. Direct key match
  if (ARTIST_AVATARS[clean]) {
    return ARTIST_AVATARS[clean];
  }

  // 2. Exact lowercase match
  for (const [key, url] of Object.entries(ARTIST_AVATARS)) {
    const k = key.toLowerCase();
    if (clean === k) return url;
  }

  // 3. Clean contains key (e.g. "Mohamed Hamaki" contains "hamaki")
  for (const [key, url] of Object.entries(ARTIST_AVATARS)) {
    const k = key.toLowerCase();
    if (k.length >= 3 && clean.includes(k)) {
      return url;
    }
  }

  // 4. Key contains clean ONLY if query has at least 4 characters to avoid false short matches
  for (const [key, url] of Object.entries(ARTIST_AVATARS)) {
    const k = key.toLowerCase();
    if (clean.length >= 4 && k.includes(clean)) {
      return url;
    }
  }

  return null;
}

